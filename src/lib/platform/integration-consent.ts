/**
 * The consent screen's content and version — INTEGRATION_SPRINT.md §3 / I5.5.
 *
 * ─── WHY A STANDALONE SCREEN AND NOT A CHECKBOX ──────────────────────────
 *
 * A ToS checkbox at signup is statutorily not consent in Illinois, and this
 * vertical's material is the reason the distinction bites: somebody describing a
 * near-death experience to a machine is disclosing something they have told
 * almost nobody, in a state where the law has no compliance path for an AI doing
 * anything that looks like care. So the screen is its own moment, it says what
 * this is in plain sentences, and the row it writes records which version they
 * were shown.
 *
 * ─── WHERE IT LANDS ──────────────────────────────────────────────────────
 *
 * BEFORE TURN 2, never before turn 1. EXPERIENCE §5.2 puts nothing between a
 * person and the box the first time — no account, no email, no age gate — and
 * that ordering is a product decision with a reason: the people this is for have
 * usually been handled by every system they tried to tell. The first thing that
 * happens to them here is being answered.
 *
 * ⚠️ These are pre-launch drafts, in the same state as the rest of the legal set
 * (`legal.ts`): wired, versioned and logged, pending the professional review
 * that E15.6/I11 own. They are not final published terms.
 */

