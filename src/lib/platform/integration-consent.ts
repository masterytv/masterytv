/** The 18+ gate. Its own attestation, stored on the row, never inferred. */
export const INTEGRATION_AGE_ATTESTATION = "I am 18 or older.";

/**
 * What the screen writes. Exported so the write path and any test agree on the
 * shape without either one restating it.
 */
export function buildConsentRow(userId: string): {
  user_id: string;
  program: string;
  version: string;
  age_attested: boolean;
  disclosures: Record<string, string>;
} {
  return {
    user_id: userId,
    program: "integration",
    version: INTEGRATION_CONSENT_VERSION,
    // Only ever written from a screen where the attestation was checked; the
    // column exists so the row can never be silent about it.
    age_attested: true,
    // The titles they were actually shown, keyed. A later revision can change
    // the set without a migration, and an old row still says what it said.
    disclosures: Object.fromEntries(INTEGRATION_DISCLOSURES.map((d) => [d.key, d.title])),
  };
}
